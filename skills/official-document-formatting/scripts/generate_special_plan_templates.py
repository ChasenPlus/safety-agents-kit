from docx.oxml import OxmlElement

TITLE_FONT = "黑体"
BODY_FONT = "仿宋_GB2312"
KAI_FONT = "楷体_GB2312"
RED = RGBColor(0xC0, 0x00, 0x00)


def set_cjk(run, font=BODY_FONT, size=14, bold=False, color=None):
    run.font.name = font
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = OxmlElement("w:rFonts")
        rpr.append(rfonts)
    rfonts.set(qn("w:eastAsia"), font)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color


def h1(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(12)
    p.paragraph_format.space_after = Pt(6)
    set_cjk(p.add_run(text), TITLE_FONT, 16, True)


def h2(doc, text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(6)
    set_cjk(p.add_run(text), KAI_FONT, 14, True)


def body(doc, text, bold=False, red=False):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(28)
    p.paragraph_format.line_spacing = 1.5
    set_cjk(p.add_run(text), BODY_FONT, 14, bold, RED if red else None)


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph()
        p.paragraph_format.first_line_indent = Pt(28)
        p.paragraph_format.line_spacing = 1.5
        set_cjk(p.add_run(it), BODY_FONT, 14)


