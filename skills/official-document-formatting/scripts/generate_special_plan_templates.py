def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--only", nargs="*", default=None)
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    sel = [t for t in TEMPLATES if args.only is None or t["id"] in args.only]
    if not sel:
        print("no template matched --only"); sys.exit(1)
    for t in sel:
        p = build(t, args.out)
        print(f"[ok] {t['id']} -> {os.path.basename(p)}")
    print(f"done: {len(sel)} templates")


if __name__ == "__main__":
    main()
