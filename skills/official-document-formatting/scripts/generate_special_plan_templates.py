    h2(doc, "（二）工艺流程"); body(doc, "【填写】工艺流程图（附框图），标明关键工序与停止点、见证点。")
    h2(doc, "（三）施工方法与操作要求"); bullets(doc, ["【要点】%s" % p_ for p_ in t["tech"]])
